#!/usr/bin/env python3
"""Write requirements.lock: every package the app needs, pinned to an exact
version and to the SHA-256 of the file pip would install on this machine.

    python scripts/lock_requirements.py            # refresh the lock (needs network)
    pip install --require-hashes -r requirements.lock

With --require-hashes pip refuses any download whose content differs from what
was locked, so a tampered or swapped package cannot be installed. The lock is
for this platform and Python version; re-run it after changing requirements.txt
or upgrading Python.
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.txt"
LOCK = ROOT / "requirements.lock"


def resolve() -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        report, pinned = Path(tmp) / "report.json", Path(tmp) / "installed.txt"
        # Lock the versions that are installed (and tested) here, not whatever is newest today.
        frozen = subprocess.run([sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
                                check=True, capture_output=True, text=True).stdout
        pinned.write_text("\n".join(ln for ln in frozen.splitlines() if "==" in ln) + "\n", encoding="utf-8")
        subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "--dry-run", "--ignore-installed",
                        "--only-binary", ":all:", "--report", str(report),
                        "-r", str(REQUIREMENTS), "-c", str(pinned)], check=True)
        return json.loads(report.read_text(encoding="utf-8"))["install"]


def render(items: list[dict]) -> str:
    lines = ["# Generated by scripts/lock_requirements.py - do not edit by hand.",
             f"# Python {sys.version_info.major}.{sys.version_info.minor} on {sys.platform}.",
             "# Install with:  pip install --require-hashes -r requirements.lock", ""]
    for item in sorted(items, key=lambda i: i["metadata"]["name"].lower()):
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        digest = item["download_info"]["archive_info"]["hashes"]["sha256"]
        lines.append(f"{name}=={version} \\\n    --hash=sha256:{digest}")
    return "\n".join(lines) + "\n"


def main() -> int:
    items = resolve()
    LOCK.write_text(render(items), encoding="utf-8")
    print(f"Locked {len(items)} packages in {LOCK.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
